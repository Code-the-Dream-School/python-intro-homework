# Warmup 1: List Operations
numbers = [14, 47, 78, 3, 59, 22, 86, 40]

print("First:    ", numbers[0])
print("Last:     ", numbers[-1])          # negative index counts from the end
print("Middle:   ", numbers[2:6])         # indexes 2-5 are the middle four of 8
print("Reversed: ", numbers[::-1])        # step of -1 walks the list backwards
